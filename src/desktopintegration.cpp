QString DesktopIntegration::shellQuote(const QString &argument) {
    QString result = argument; result.replace('\'', "'\\''"); return '\'' + result + '\'';
}

QString DesktopIntegration::desktopQuote(const QString &argument) {
    QString result = "\"";
    for (const QChar ch : argument) {
        if (ch == '\\') result += QString(4, '\\');
        else if (ch == '"' || ch == '$' || ch == '`') result += QString(2, '\\') + ch;
        else if (ch == '%') result += "%%";
        else if (ch == '\n') result += "\\n";
        else if (ch == '\r') result += "\\r";
        else result += ch;
    }
    return result + '"';
}

bool DesktopIntegration::install(const QString &executable, QString *error) {
#ifdef Q_OS_WIN
    return windowsShortcut(executable, false, error);
#elif defined(Q_OS_LINUX) && !defined(Q_OS_ANDROID)
    const QByteArray script = "#!/bin/sh\n# " + Marker + "\nexec " + shellQuote(executable).toUtf8() + " --share -- \"$@\"\n";
    if (!writeOwned(dataFile("nautilus/scripts/Send with Dukto"), script, true, error)) return false;
    // env keeps a literal '%' in the executable path out of launchers' early
    // executable lookup (before they expand %% according to the desktop spec).
    const QByteArray service = "# " + Marker + "\n[Desktop Entry]\nType=Service\nMimeType=application/octet-stream;inode/directory;\nActions=SendWithDukto;\nX-KDE-Priority=TopLevel\n\n[Desktop Action SendWithDukto]\nName=Send with Dukto\nIcon=dukto\nExec=/usr/bin/env -- " + desktopQuote(executable).toUtf8() + " --share -- %U\n";
    return writeOwned(dataFile("kio/servicemenus/dukto-send.desktop"), service, true, error);
#else
    Q_UNUSED(executable);
    *error = QObject::tr("File-manager actions are available on Linux and Windows."); return false;
#endif
}

bool DesktopIntegration::remove(QString *error) {
#ifdef Q_OS_WIN
    return windowsShortcut({}, true, error);
#elif defined(Q_OS_LINUX) && !defined(Q_OS_ANDROID)
    for (const auto &path : {dataFile("nautilus/scripts/Send with Dukto"), dataFile("kio/servicemenus/dukto-send.desktop")}) {
        QFile file(path);
        if (!file.exists()) continue;
        if (!file.open(QIODevice::ReadOnly)) { *error = file.errorString(); return false; }
        const bool ours = file.readAll().contains(Marker); file.close();
        if (ours && !file.remove()) { *error = file.errorString(); return false; }
    }
    return true;
#else
    Q_UNUSED(error); return true;
#endif
}

void DesktopIntegration::ensureInstalled(const QString &executable) {
#if defined(Q_OS_WIN) || (defined(Q_OS_LINUX) && !defined(Q_OS_ANDROID))
    QSettings settings("dukto", "Dukto");
    if (!settings.value("Desktop/FileActionsEnabled", true).toBool()) return;
    if (settings.value("Desktop/FileActionsExecutable").toString() == executable) return;
    QString error;
    if (install(executable, &error)) settings.setValue("Desktop/FileActionsExecutable", executable);
    else qWarning().noquote() << error;
#else
    Q_UNUSED(executable);
#endif
}
