const QByteArray Marker("Generated by Dukto file actions v1");
#ifndef Q_OS_WIN
QString dataFile(const QString &relative) {
    return QDir(QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation)).filePath(relative);
}
bool writeOwned(const QString &path, const QByteArray &content, bool executable, QString *error) {
    QFile old(path);
    if (old.exists()) {
        if (!old.open(QIODevice::ReadOnly)) { *error = old.errorString(); return false; }
        const auto previous = old.readAll();
        if (!previous.contains(Marker)) { *error = QObject::tr("A custom file already exists at %1. It was left unchanged.").arg(path); return false; }
        if (previous == content) {
            if (!executable || old.permissions().testFlag(QFileDevice::ExeOwner)) return true;
            if (old.setPermissions(QFileDevice::ReadOwner | QFileDevice::WriteOwner | QFileDevice::ExeOwner)) return true;
            *error = old.errorString(); return false;
        }
    }
    if (!QDir().mkpath(QFileInfo(path).absolutePath())) { *error = QObject::tr("Cannot create the file-manager actions folder."); return false; }
    QSaveFile file(path);
    if (!file.open(QIODevice::WriteOnly) || file.write(content) != content.size() || !file.commit()) { *error = file.errorString(); return false; }
    return !executable || QFile::setPermissions(path, QFileDevice::ReadOwner | QFileDevice::WriteOwner | QFileDevice::ExeOwner);
}
#endif
#ifdef Q_OS_WIN
QString shortcutPath() {
    PWSTR folder = nullptr;
    if (FAILED(SHGetKnownFolderPath(FOLDERID_SendTo, KF_FLAG_CREATE, nullptr, &folder))) return {};
    QString path = QDir(QString::fromWCharArray(folder)).filePath("Dukto.lnk");
    CoTaskMemFree(folder); return path;
}
bool windowsShortcut(const QString &executable, bool removing, QString *error) {
    const auto path = shortcutPath();
    if (path.isEmpty()) { *error = QObject::tr("Cannot find the Windows Send to folder."); return false; }
    const HRESULT initialized = CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED);
    IShellLinkW *link = nullptr; IPersistFile *file = nullptr;
    HRESULT status = CoCreateInstance(CLSID_ShellLink, nullptr, CLSCTX_INPROC_SERVER, IID_PPV_ARGS(&link));
    if (SUCCEEDED(status)) status = link->QueryInterface(IID_PPV_ARGS(&file));
    if (SUCCEEDED(status) && QFileInfo::exists(path)) {
        status = file->Load(reinterpret_cast<LPCOLESTR>(path.utf16()), STGM_READ);
        wchar_t description[256] = {};
        if (SUCCEEDED(status)) status = link->GetDescription(description, 256);
        if (SUCCEEDED(status) && QString::fromWCharArray(description) != QString::fromLatin1(Marker)) {
            *error = QObject::tr("A custom Dukto shortcut already exists. It was left unchanged.");
            status = E_ACCESSDENIED;
        }
    }
    if (SUCCEEDED(status)) {
        if (removing) {
            if (QFileInfo::exists(path) && !QFile::remove(path)) status = E_ACCESSDENIED;
        } else {
            const QString native = QDir::toNativeSeparators(QFileInfo(executable).absoluteFilePath());
            status = link->SetPath(reinterpret_cast<LPCWSTR>(native.utf16()));
            if (SUCCEEDED(status)) status = link->SetArguments(L"--share --");
            if (SUCCEEDED(status)) status = link->SetDescription(reinterpret_cast<LPCWSTR>(QString::fromLatin1(Marker).utf16()));
            if (SUCCEEDED(status)) status = link->SetIconLocation(reinterpret_cast<LPCWSTR>(native.utf16()), 0);
            if (SUCCEEDED(status)) status = file->Save(reinterpret_cast<LPCOLESTR>(path.utf16()), TRUE);
        }
    }
    if (file) file->Release();
    if (link) link->Release();
    if (SUCCEEDED(initialized)) CoUninitialize();
    if (FAILED(status) && error->isEmpty()) *error = QObject::tr("Cannot update the Windows Send to shortcut (0x%1).").arg(quint32(status), 8, 16, QLatin1Char('0'));
    return SUCCEEDED(status);
}
#endif
